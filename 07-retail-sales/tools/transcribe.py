def step(p, freq, k):
    y, m = map(int, p.split("-"))
    n = {"M": 1, "Q": 3, "FY": 12}[freq] * k
    t = y * 12 + (m - 1) + n
    return f"{t // 12}-{t % 12 + 1:02d}"


QSAS_DATE = {"QSAS226": "1956-12", "QSAS238": "1959-12", "QSAS254": "1964-12"}


def issue_date(issue):
    """Reference period of the issue (used to pick the latest print)."""
    if issue in QSAS_DATE:
        return QSAS_DATE[issue]
    m = re.match(r"RS(\d{4})-(\d{2})", issue)
    return f"{m.group(1)}-{m.group(2)}"


def rows():
    out = []
    for issue, page, freq, first, basis, measure, unit, vals, note in B:
        for i, v in enumerate(vals):
            if v is None:
                continue
            out.append((issue, issue_date(issue), page, freq, step(first, freq, i), basis, measure, unit, v, note))
    return out


